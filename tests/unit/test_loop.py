async def test_an_oversized_batch_is_discarded_whole() -> None:
    """No subset runs, because which subset would depend on provider ordering."""
    executed: list[str] = []

    async def record(**kwargs: object) -> str:
        executed.append("ran")
        return "ok"

    limits = LoopLimits(max_tool_calls_per_turn=2)
    model = FakeModel(
        [
            turn(*[call("get_logs", {"i": i}, id=f"c{i}") for i in range(5)]),
            turn(call(SUBMIT, {"ok": True}, id="s")),
        ]
    )
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch={**DISPATCH, "get_logs": record},
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
        limits=limits,
    )
    assert result.submitted
    assert executed == []
    assert any(control("oversized_batch_discarded") == m.get("content") for m in result.transcript)


async def test_a_submission_beside_other_calls_is_rejected_but_the_others_still_run() -> None:
    """The submission is premature by construction; the investigation is not wasted."""
    model = FakeModel(
        [
            turn(call("get_logs", {"q": "a"}, id="t1"), call(SUBMIT, {"ok": True}, id="s1")),
            turn(call(SUBMIT, {"ok": True}, id="s2")),
        ]
    )
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
    )
    assert result.submitted
    assert result.tool_calls_made == 1
    rejection = mixed_submit_message(SUBMIT)
    assert any(m.get("content") == f"error: {rejection}" for m in result.transcript)
    assert any(m["role"] == "user" and m["content"] == rejection for m in result.transcript)


async def test_the_guard_stops_being_consulted_after_its_limit() -> None:
    """A guard that will never be satisfied must not consume the whole budget."""
    consulted = 0

    def guard(args: dict, calls: int, messages: list) -> str:
        nonlocal consulted
        consulted += 1
        return "not yet"

    model = FakeModel([turn(call(SUBMIT, {"ok": True}, id=f"s{i}")) for i in range(4)])
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
        submit_guard=guard,
        limits=LoopLimits(submit_guard_rejections=2),
    )
    assert result.submitted
    assert consulted == 2


async def test_guard_material_is_not_framed_as_an_error() -> None:
    """A guard handing the model something to weigh is not reporting a fault.

    Framed as an error the model discards it, which defeats the mechanism.
    """

    def guard(args: dict, calls: int, messages: list) -> str:
        return "note: a past incident used a different fix"

    # Rejected twice, then the guard is no longer consulted and the third is accepted.
    model = FakeModel([turn(call(SUBMIT, {"ok": True}, id=f"s{i}")) for i in range(3)])
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
        submit_guard=guard,
    )
    assert result.submitted
    handed_back = [m for m in result.transcript if m["role"] == "tool"]
    assert handed_back[0]["content"] == "note: a past incident used a different fix"


async def test_repeated_invalid_submissions_end_the_stage() -> None:
    """Parse failures and validation failures share one retry budget."""

    def validator(args: dict) -> None:
        raise ValueError("missing evidence")

    model = FakeModel([turn(call(SUBMIT, {"ok": True}, id=f"s{i}")) for i in range(5)])
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
        submit_validator=validator,
        limits=LoopLimits(submit_validation_rejections=3),
    )
    assert result.status == "submit_validation_failed"
    assert "missing evidence" in (result.reason or "")


async def test_a_guarded_stage_is_not_rescued_before_it_has_acted() -> None:
    """A rescue converts findings into a submission. With no findings there is nothing
    to convert, and rescuing anyway manufactures a confident-looking empty answer."""

    def guard(args: dict, calls: int, messages: list) -> None:
        return None

    prose = "x" * 900
    model = FakeModel([turn(text=prose) for _ in range(3)])
    sink = ListSink()
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
        submit_guard=guard,
        journal=Journal(sink, session_id="s1", stage="rca"),
    )
    assert result.status == "no_tool_calls"
    rescues = [
        e
        for e in sink.events
        if isinstance(e.payload, InterventionEvent) and e.payload.control == "finalizer_rescue"
    ]
    assert rescues == []


def test_the_turn_budget_leaves_room_for_the_rescue_it_may_grant() -> None:
    """A rescue requested after the last normal turn has to be answerable."""
    limits = LoopLimits(max_turns=20, finalizer_rescues=1, submit_validation_rejections=3)
    assert limits.turn_budget == 23
    assert LoopLimits(max_turns=20, finalizer_rescues=0).turn_budget == 20
