import json
import pathlib

import pytest

from kira.audit.journal import Journal, ListSink
from kira.contracts.events import InterventionEvent
from kira.llm.types import ModelRequest, ModelResponse, ToolCall, ToolSpec, Usage
from kira.roles.loop import run_until_submit
from kira.roles.policy import (
    LoopLimits,
    compact_rescue_context,
    control,
    finalizer_rescue_message,
    mixed_submit_message,
    no_tool_nudge_message,
    repeat_breaker_message,
)

FIXTURE = (
    pathlib.Path(__file__).resolve().parents[1] / "fixtures" / "prototype_control_messages.json"
)
PROTOTYPE = json.loads(FIXTURE.read_text(encoding="utf-8"))

SUBMIT = "submit_root_cause"


def spec(name: str) -> ToolSpec:
    return ToolSpec(name=name, description=name, parameters={"type": "object"})


TOOLS = [spec("get_logs"), spec("get_metrics"), spec("get_traces"), spec(SUBMIT)]


def call(name: str, arguments: dict, *, id: str = "c1", parse_error: str | None = None) -> ToolCall:
    return ToolCall(
        id=id,
        name=name,
        arguments=arguments,
        raw_arguments=json.dumps(arguments),
        parse_error=parse_error,
    )


def turn(*calls: ToolCall, text: str | None = None, finish: str = "stop") -> ModelResponse:
    return ModelResponse(
        text=text,
        tool_calls=tuple(calls),
        finish_reason=finish,
        reasoning=None,
        usage=Usage(),
        duration_ms=1,
        attempts=1,
    )


class FakeModel:
    """Replays scripted turns and records what it was asked."""

    def __init__(self, turns: list[ModelResponse]) -> None:
        self.turns = list(turns)
        self.requests: list[ModelRequest] = []

    async def complete(self, request: ModelRequest, *, caller: str) -> ModelResponse:
        self.requests.append(request)
        if not self.turns:
            raise AssertionError("the loop took more turns than the test scripted")
        return self.turns.pop(0)


async def echo(**kwargs: object) -> str:
    return f"result for {sorted(kwargs)}"


DISPATCH = {"get_logs": echo, "get_metrics": echo, "get_traces": echo, SUBMIT: echo}


# --- fidelity: the text the model actually receives ------------------------------


@pytest.mark.parametrize("key", sorted(k for k in PROTOTYPE if k != "compact_rescue"))
def test_control_messages_are_byte_identical_to_the_prototype(key: str) -> None:
    """Corrective wording is a held-constant input to every published measurement.

    These strings are what the harness says to the model when it leaves the protocol.
    A reworded nudge is a different intervention, so the fixture is generated by
    calling the prototype's own renderers rather than by copying the files.
    """
    rendered = {
        "no_tool": lambda: no_tool_nudge_message(
            submit_tool=SUBMIT,
            finish_reason="stop",
            assistant_content="some prose",
            tool_call_truncated=False,
            token_limited=False,
        ),
        "no_tool_truncated": lambda: no_tool_nudge_message(
            submit_tool=SUBMIT,
            finish_reason="length",
            assistant_content="x",
            tool_call_truncated=True,
            token_limited=True,
        ),
        "no_tool_max_tokens_with_content": lambda: no_tool_nudge_message(
            submit_tool=SUBMIT,
            finish_reason="length",
            assistant_content="partial output",
            tool_call_truncated=False,
            token_limited=True,
        ),
        "no_tool_max_tokens_empty": lambda: no_tool_nudge_message(
            submit_tool=SUBMIT,
            finish_reason="length",
            assistant_content="",
            tool_call_truncated=False,
            token_limited=True,
        ),
        "repeat_soft": lambda: repeat_breaker_message(
            tools=["get_logs"], count=3, submit_tool=SUBMIT
        ),
        "repeat_soft_multi": lambda: repeat_breaker_message(
            tools=["get_logs", "get_metrics"], count=4, submit_tool=SUBMIT
        ),
        "repeat_strong_with_alts": lambda: repeat_breaker_message(
            tools=["get_logs"],
            count=6,
            submit_tool=SUBMIT,
            alternatives=["get_traces", "get_metrics"],
            strong=True,
        ),
        "repeat_strong_no_alts": lambda: repeat_breaker_message(
            tools=["get_logs"], count=6, submit_tool=SUBMIT, alternatives=[], strong=True
        ),
        "mixed_submit": lambda: mixed_submit_message(SUBMIT),
        "finalizer_rescue": lambda: finalizer_rescue_message(
            submit_tool=SUBMIT, reason="max_turns_exceeded"
        ),
        "tool_failure_guidance": lambda: control("tool_failure_guidance"),
    }[key]()
    assert rendered == PROTOTYPE[key]


def test_compact_rescue_context_matches_the_prototype() -> None:
    """The rescue brief's section order, truncation and joining are all load-bearing."""
    built = compact_rescue_context(
        initial_messages=[
            {"role": "user", "content": "task A"},
            {"role": "user", "content": "task B"},
        ],
        transcript=[
            {"role": "assistant", "content": "thinking about it"},
            {"role": "tool", "content": "result one"},
            {"role": "tool", "content": "result two"},
            {"role": "assistant", "content": "my conclusion"},
        ],
        submit_tool=SUBMIT,
        reason="repeated_call_no_progress",
        limits=LoopLimits(),
    )
    assert built == PROTOTYPE["compact_rescue"]


# --- defects this rebuild fixes --------------------------------------------------


async def test_a_varying_rationale_no_longer_hides_a_repeated_call() -> None:
    """The breaker keys on the call, not on the model's prose about the call.

    Every non-submit tool schema carries a required ``rationale``. The prototype put it
    in the repeat signature, so a model reissuing one identical query while rewording a
    sentence of reasoning produced a fresh signature every turn and never tripped the
    breaker that exists to stop exactly that spiral.
    """
    model = FakeModel(
        [
            turn(call("get_logs", {"q": "x", "rationale": f"attempt number {i}"}, id=f"c{i}"))
            for i in range(3)
        ]
        + [turn(call(SUBMIT, {"ok": True}, id="s"))]
    )
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
    )
    assert result.submitted
    correctives = [
        m
        for m in result.transcript
        if m["role"] == "user" and "received the same result" in str(m["content"])
    ]
    assert correctives, "three identical calls should have tripped the soft tier"


async def test_a_rescue_context_never_holds_an_unanswered_tool_call() -> None:
    """Every assistant tool call in the rescue brief has its matching result.

    A rescue restricts the offered schema but not the dispatch map, so a model can still
    call a real investigation tool on a rescue turn. The prototype appended that
    assistant message to the rescue context and its results only to the main transcript,
    building a request whose tool call had no answer — which an OpenAI-compatible server
    rejects outright.
    """
    prose = "x" * 900  # clears the evidence threshold so the rescue is granted
    model = FakeModel(
        [
            turn(text=prose),
            turn(text=prose),
            turn(text=prose),
            turn(call("get_logs", {"q": "y"}, id="r1")),
            turn(call(SUBMIT, {"ok": True}, id="s")),
        ]
    )
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
    )
    assert result.submitted

    sent = model.requests[-1].messages
    answered = {m["tool_call_id"] for m in sent if m["role"] == "tool"}
    for message in sent:
        for pending in message.get("tool_calls") or []:
            assert pending["id"] in answered, "rescue context would be rejected as malformed"


