def spec(name: str) -> ToolSpec:
    return ToolSpec(name=name, description=name, parameters={"type": "object"})


TOOLS = [spec("get_logs"), spec("get_metrics"), spec("get_traces"), spec(SUBMIT)]


def call(name: str, arguments: dict, *, id: str = "c1", parse_error: str | None = None) -> ToolCall:
    return ToolCall(
        id=id,
        name=name,
        arguments=arguments,
        raw_arguments=json.dumps(arguments),
        parse_error=parse_error,
    )


def turn(*calls: ToolCall, text: str | None = None, finish: str = "stop") -> ModelResponse:
    return ModelResponse(
        text=text,
        tool_calls=tuple(calls),
        finish_reason=finish,
        reasoning=None,
        usage=Usage(),
        duration_ms=1,
        attempts=1,
    )


class FakeModel:
    """Replays scripted turns and records what it was asked."""

    def __init__(self, turns: list[ModelResponse]) -> None:
        self.turns = list(turns)
        self.requests: list[ModelRequest] = []

    async def complete(self, request: ModelRequest, *, caller: str) -> ModelResponse:
        self.requests.append(request)
        if not self.turns:
            raise AssertionError("the loop took more turns than the test scripted")
        return self.turns.pop(0)


async def echo(**kwargs: object) -> str:
    return f"result for {sorted(kwargs)}"


DISPATCH = {"get_logs": echo, "get_metrics": echo, "get_traces": echo, SUBMIT: echo}


