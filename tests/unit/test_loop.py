async def test_a_varying_rationale_no_longer_hides_a_repeated_call() -> None:
    """The breaker keys on the call, not on the model's prose about the call.

    Every non-submit tool schema carries a required ``rationale``. The prototype put it
    in the repeat signature, so a model reissuing one identical query while rewording a
    sentence of reasoning produced a fresh signature every turn and never tripped the
    breaker that exists to stop exactly that spiral.
    """
    model = FakeModel(
        [
            turn(call("get_logs", {"q": "x", "rationale": f"attempt number {i}"}, id=f"c{i}"))
            for i in range(3)
        ]
        + [turn(call(SUBMIT, {"ok": True}, id="s"))]
    )
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
    )
    assert result.submitted
    correctives = [
        m
        for m in result.transcript
        if m["role"] == "user" and "received the same result" in str(m["content"])
    ]
    assert correctives, "three identical calls should have tripped the soft tier"


async def test_a_rescue_context_never_holds_an_unanswered_tool_call() -> None:
    """Every assistant tool call in the rescue brief has its matching result.

    A rescue restricts the offered schema but not the dispatch map, so a model can still
    call a real investigation tool on a rescue turn. The prototype appended that
    assistant message to the rescue context and its results only to the main transcript,
    building a request whose tool call had no answer — which an OpenAI-compatible server
    rejects outright.
    """
    prose = "x" * 900  # clears the evidence threshold so the rescue is granted
    model = FakeModel(
        [
            turn(text=prose),
            turn(text=prose),
            turn(text=prose),
            turn(call("get_logs", {"q": "y"}, id="r1")),
            turn(call(SUBMIT, {"ok": True}, id="s")),
        ]
    )
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
    )
    assert result.submitted

    sent = model.requests[-1].messages
    answered = {m["tool_call_id"] for m in sent if m["role"] == "tool"}
    for message in sent:
        for pending in message.get("tool_calls") or []:
            assert pending["id"] in answered, "rescue context would be rejected as malformed"


async def test_the_rescue_turn_is_reconstructible_from_the_log() -> None:
    """A rescued run's decisive turn was sent messages that existed nowhere afterwards.

    The rescue does not append to the transcript, it replaces it: the kickoff the run
    returns is not what the rescue turn received, and the brief that was received was
    kept beside the transcript and discarded with the run. Since the submission a rescue
    produces is the answer the whole stage is graded on, a run's record could not say
    what that answer was made from. The intervention that opened the rescue is where the
    brief now lives, and it is the only event that carries text for this reason.
    """
    prose = "x" * 900  # clears the evidence threshold so the rescue is granted
    model = FakeModel(
        [
            turn(call("get_logs", {"q": "a"}, id="t1")),
            turn(text=prose),
            turn(text=prose),
            turn(text=prose),
            turn(call(SUBMIT, {"ok": True}, id="s")),
        ]
    )
    sink = ListSink()
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
        journal=Journal(sink, session_id="s1", stage="rca"),
    )
    assert result.submitted

    [rescue] = [
        e.payload
        for e in sink.events
        if isinstance(e.payload, InterventionEvent) and e.payload.control == "finalizer_rescue"
    ]
    sent = list(model.requests[-1].messages)
    assert rescue.context == sent
    # The half the transcript cannot supply: the brief itself was never part of it.
    assert sent[-1] not in result.transcript


async def test_a_retrieval_call_records_which_records_it_served() -> None:
    """Which precedents a role was served is what every analysis of this mechanism asks.

    The gated second pass records its own retrieval richly. A role's did not: the event
    carried the query and the size of the answer, while the record identifiers lived in
    the run's alias map and died with the process — and the model-facing text shows only
    the `memory-N` handle, so the answer was not recoverable from the transcript either.
    """
    served = ({"record_id": "sess-aaa", "handle": "memory-1", "score": 0.91},)

    async def retrieving(**kwargs: object) -> ToolOutput:
        return ToolOutput("[memory-1]  score=0.910", served)

    model = FakeModel(
        [
            turn(call("memory_search", {"query": "crashloop", "rationale": "why"}, id="m1")),
            turn(call(SUBMIT, {"ok": True}, id="s")),
        ]
    )
    sink = ListSink()
    result = await run_until_submit(
        model=model,
        role="rca",
        system="s",
        tools=[spec("memory_search"), spec(SUBMIT)],
        dispatch={"memory_search": retrieving, SUBMIT: echo},
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
        journal=Journal(sink, session_id="s1", stage="rca"),
    )
    assert result.submitted

    [event] = [e.payload for e in sink.events if isinstance(e.payload, ToolCallEvent)]
    assert event.retrieval == list(served)
    # Audit-only, on the way out as well as in: the model reads the text and nothing else.
    assert all("sess-aaa" not in str(m.get("content")) for m in result.transcript)


async def test_a_spiral_that_also_submits_is_still_a_spiral() -> None:
    """Both circuit breakers were silent whenever the turn carried a submission.

    The mixed-submit branch dispatched the other calls and then went straight back
    around: it never scored them against the repeat breaker, and it reported a
    submission-rejection count it never advanced. A model repeating one query beside a
    premature submission therefore spent its entire turn budget with neither control
    firing and with every rejection in the log reading as the first one.
    """
    turns = [
        turn(call("get_logs", {"q": "x"}, id=f"t{i}"), call(SUBMIT, {"ok": True}, id=f"s{i}"))
        for i in range(20)
    ]
    sink = ListSink()
    result = await run_until_submit(
        model=FakeModel(turns),
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
        # No rescue, so the breaker's own verdict is what ends the run.
        limits=LoopLimits(finalizer_rescues=0),
        journal=Journal(sink, session_id="s1", stage="rca"),
    )

    assert result.status == "repeated_call_no_progress"
    assert result.turns_used == LoopLimits().repeat_stop
    breaks = [
        e.payload
        for e in sink.events
        if isinstance(e.payload, InterventionEvent) and e.payload.control == "repeat_breaker"
    ]
    assert [b.action for b in breaks][-1] == "ended_run"
    attempts = [
        e.payload.attempt
        for e in sink.events
        if isinstance(e.payload, SubmissionEvent) and not e.payload.accepted
    ]
    assert attempts == list(range(1, len(attempts) + 1))


async def test_a_bundled_submission_does_not_spend_the_schema_repair_budget() -> None:
    """A submission emitted beside investigation tools is handed back unread.

    It was charged to the same three-attempt budget the parse and validation rejections
    spend from, and that branch never checked the cap it was spending. Two bundled
    submits therefore turned a three-attempt schema repair into a one-attempt one and
    ended the stage with no artifact on the first fixable slip, where the archive
    charged a bundled submission nothing at all.
    """
    consulted = 0

    def validator(arguments: dict) -> None:
        nonlocal consulted
        consulted += 1
        raise ValueError("confidence must be at most 1")

    # Distinct arguments on every turn, so the repeat breaker stays out of it.
    turns = [
        turn(call("get_logs", {"q": i}, id=f"m{i}"), call(SUBMIT, {"n": i}, id=f"b{i}"))
        for i in range(2)
    ]
    turns += [turn(call(SUBMIT, {"n": 10 + i}, id=f"v{i}")) for i in range(3)]

    result = await run_until_submit(
        model=FakeModel(turns),
        role="rca",
        system="s",
        tools=TOOLS,
        dispatch=DISPATCH,
        submit_tool=SUBMIT,
        messages=[{"role": "user", "content": "go"}],
        submit_validator=validator,
    )

    assert result.status == "submit_validation_failed"
    assert consulted == LoopLimits().submit_validation_rejections


